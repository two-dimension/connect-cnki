$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$pythonPath = Join-Path $projectRoot '.venv/Scripts/python.exe'
$configPath = Join-Path $projectRoot 'config.local.json'
if (-not (Test-Path -LiteralPath $pythonPath) -or -not (Test-Path -LiteralPath $configPath)) {
    throw 'Run scripts/setup.ps1 first.'
}
$codexDir = Join-Path $projectRoot '.codex'
$targetPath = Join-Path $codexDir 'config.toml'
New-Item -ItemType Directory -Force -Path $codexDir | Out-Null
$existing = if (Test-Path -LiteralPath $targetPath) { Get-Content -LiteralPath $targetPath -Raw -Encoding UTF8 } else { '' }
if ($existing -match '(?m)^\s*\[mcp_servers\.cnki_literature\]\s*$') {
    Write-Output 'Project MCP entry already exists; existing settings preserved.'
    exit 0
}
$commandToml = ConvertTo-Json -InputObject $pythonPath -Compress
$argsToml = ConvertTo-Json -InputObject @('-m', 'cnki_mcp', '--config', $configPath) -Compress
$cwdToml = ConvertTo-Json -InputObject $projectRoot -Compress
$block = @"

# Generated by scripts/register-codex.ps1. Local project only.
[mcp_servers.cnki_literature]
command = $commandToml
args = $argsToml
cwd = $cwdToml
startup_timeout_sec = 20
tool_timeout_sec = 60

[mcp_servers.cnki_literature.env]
PYTHONUTF8 = "1"
"@
[System.IO.File]::WriteAllText($targetPath, ($existing.TrimEnd() + "`n" + $block + "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Output 'Registered project-local cnki_literature. Restart the MCP connection or open a new trusted project chat.'
